// Revenir chaque jour : cartes dues dès le matin, accueil de celui qui revient, fin de séance, rappels gratuits.
const { chromium } = require('playwright');
(async()=>{const b=await chromium.launch({executablePath:'/opt/pw-browsers/chromium'});const fails=[];const ok=(c,m)=>{console.log(c?'ok  ':'FAIL',m);if(!c)fails.push(m)};
const ctx=await b.newContext({viewport:{width:390,height:844}});const p=await ctx.newPage();const errs=[];p.on('pageerror',e=>errs.push(e.message));
await ctx.addInitScript(()=>{if(!localStorage.getItem('x')){localStorage.setItem('x','1');localStorage.setItem('bristol-eps-v1',JSON.stringify({prefs:{concours:'agreg-int'}}));localStorage.setItem('bristol-eps-welcome','1');}});
await p.clock.install({time:new Date('2026-10-22T21:00:00+02:00')});
await p.goto('http://localhost:8766/app/');await p.waitForTimeout(800);
await p.evaluate(()=>{setView('home')});
ok(await p.evaluate(()=>{const t=document.querySelector('#panel-home').innerHTML;return t.indexOf('trial-card')<t.indexOf('id="ts-h"')}),'jour 1 : retour offert avant la séance');
await p.evaluate(()=>{buildQueue();setView('revise')});
for(let i=0;i<5;i++)await p.evaluate(i=>{flipped=true;grade(i<2?'hesite':'su')},i);
await p.evaluate(()=>render());await p.waitForTimeout(200);
const fin=await p.textContent('#panel-revise');
ok(/Demain : 2 cartes à revoir/.test(fin),'fin de séance : 2 cartes demain');
ok(/Prochaine carte à revoir demain/.test(fin),'prochaine carte : demain');
ok(/Maintenant, ton retour offert/.test(fin)&&await p.$('#panel-revise .sess-next [data-act="essai-go"]'),'fin de séance : retour offert proposé');
ok(!(await p.$('#panel-revise [data-why="new"].primary')),'fin de séance : payer n\'est plus le bouton principal');
await p.clock.setFixedTime(new Date('2026-10-23T08:00:00+02:00'));await p.reload();await p.waitForTimeout(800);
await p.evaluate(()=>setView('home'));
const h=await p.textContent('#panel-home');
ok(/2 à revoir/.test(h),'le lendemain matin : les 2 cartes sont dues ('+(h.match(/\d+ à revoir/)||['aucune'])[0]+')');
ok(await p.evaluate(()=>{const t=document.querySelector('#panel-home').innerHTML;return t.indexOf('id="ts-h"')<t.indexOf('trial-card')&&!document.querySelector('#panel-home .up-banner')&&/Débloquer tout/.test(document.querySelector('.trial-card').textContent)}),'jour 2 : séance d\'abord, offre en une seule carte');
await p.clock.setFixedTime(new Date('2026-10-27T08:00:00+02:00'));await p.reload();await p.waitForTimeout(800);
await p.evaluate(()=>setView('home'));
ok(/Content de te revoir/.test(await p.textContent('#panel-home')),'après 5 jours d\'absence : accueil du retour');
const pu=await p.evaluate(()=>{acct.status='in';return pushHTML()});
ok(!/data-why="rappel"/.test(pu),'rappels sans cadenas pour un compte gratuit');
ok(!errs.length,'sans erreur '+errs.join('|'));
console.log(fails.length?'FAILS: '+fails.join(' | '):'ALL OK');await b.close();})();
